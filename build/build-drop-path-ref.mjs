#!/usr/bin/env node
/**
 * build-drop-path-ref — assemble the committed browser bundle for
 * plugins/dsh-drop-path-ref.
 *
 *   node build/build-drop-path-ref.mjs
 *
 * Sources: lib/paths.mjs (tested pure helpers, `export ` keywords stripped)
 * + lib/client-entry.js (DOM/i18n/registration body). Output:
 * lib/client.js in the `window.__ModuleLoader__` bundle format, same as the
 * other web-only plugins. No esbuild needed — plain concatenation.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PLUGIN = join(ROOT, 'plugins', 'dsh-drop-path-ref');

const paths = readFileSync(join(PLUGIN, 'lib', 'paths.mjs'), 'utf8').replace(/^export /gm, '');
const entry = readFileSync(join(PLUGIN, 'lib', 'client-entry.js'), 'utf8');

const indent = (text) => text.split('\n').map((line) => (line.length > 0 ? `\t\t${line}` : line)).join('\n');

const bundle = `/*
 * GENERATED by build/build-drop-path-ref.mjs — do not edit by hand.
 * Edit plugins/dsh-drop-path-ref/lib/paths.mjs or lib/client-entry.js and
 * re-run \`node build/build-drop-path-ref.mjs\`.
 *
 * dsh-drop-path-ref (client half): files the stock image-only drop flow
 * cannot accept are inserted into the composer as absolute-path references
 * instead of being rejected. Capture-phase interception keeps the stock
 * image attachment flow untouched.
 */
window.__ModuleLoader__.load({
\tid: "dsh-drop-path-ref",
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });

${indent(paths.trim())}

${indent(entry.trim())}

\t\treturn module.exports;
\t}
});
`;

writeFileSync(join(PLUGIN, 'lib', 'client.js'), bundle);
console.log(`[build-drop-path-ref] ${bundle.length} chars -> plugins/dsh-drop-path-ref/lib/client.js`);
