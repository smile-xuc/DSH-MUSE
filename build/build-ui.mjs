#!/usr/bin/env node
/**
 * Builds the dsh-muse-ui browser half into the cordis client-bundle factory
 * format: `window.__ModuleLoader__.load({ id, factory })` with externals left
 * as `require(...)` calls resolved by the host's frozen browser module table
 * (react, react/jsx-runtime, react-dom, @deepseek-ai/cordis,
 * @deepseek-ai/dsh-client-ui-slots, @deepseek-ai/dsh-client-ui-primitives,
 * @deepseek-ai/dsh-client-runtime/client — the baseline every client bundle
 * may request). This replicates what the dsh monorepo's tsdown client preset
 * emits, so the plugin needs no dsh checkout to build.
 *
 * The artifact is committed (plugins/dsh-muse-ui/lib/client.js) so users who
 * clone DSH-MUSE never need to run this; rebuild only after changing src/ or
 * when bumping the DSH compatibility target.
 */
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'plugins', 'dsh-muse-ui', 'lib', 'client.js');

const result = await build({
  entryPoints: [join(ROOT, 'plugins', 'dsh-muse-ui', 'src', 'client.jsx')],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  jsx: 'automatic',
  /* the browser module-table baseline; everything else is bundled in */
  external: ['react', 'react/jsx-runtime', 'react-dom', 'react-dom/client', '@deepseek-ai/*'],
  minify: false,
  write: false,
  logLevel: 'warning',
});

const code = result.outputFiles[0].text;
const factory = `/* dsh-muse-ui client bundle — generated by build/build-ui.mjs; do not edit. */\nwindow.__ModuleLoader__.load({\n\tid: "dsh-muse-ui",\n\tfactory: (require) => {\n\t\tvar module = { exports: {} };\n\t\tvar exports = module.exports;\n${code}\n\t\treturn module.exports;\n\t}\n});\n`;

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, factory);
console.log(`[build:ui] wrote ${OUT} (${factory.length} bytes)`);
